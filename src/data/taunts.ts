/** ชื่อมีตัวอักษรละตินไหม (ตัวเลข/เว้นวรรค/จุด ไม่นับ) */
export function hasLatinLetters(name: string): boolean {
  return /[A-Za-z]/.test(name)
}

/** ชื่อมีตัวอักษรไทยไหม */
export function hasThaiLetters(name: string): boolean {
  return /[฀-๿]/.test(name)
}

/**
 * เลือกคำจิกกัดแบบกระจายตามตัวชื่อ ไม่ใช่สุ่มใหม่ทุกคีย์
 * ถ้าสุ่มทุกครั้งที่พิมพ์ ข้อความจะกระพริบเปลี่ยนไปมาจนอ่านไม่ทัน
 */
export function pickEnglishNameTaunt(name: string): string {
  const seed = [...name].reduce((sum, ch) => sum + ch.charCodeAt(0), 0)
  return ENGLISH_NAME_TAUNTS[seed % ENGLISH_NAME_TAUNTS.length]!
}

/* ==========================================================================
 * 2. ช่วงอายุ
 * ======================================================================== */

export interface AgeNote {
  emoji: string
  text: string
}

/** ข้อความเล็กๆ ใต้ช่องอายุ — null = ยังไม่ต้องพูดอะไร */
export function getAgeNote(age: number): AgeNote | null {
  if (!Number.isFinite(age) || age <= 0) return null

  if (age < 20) return { emoji: '🍼', text: 'ยังเด็ก เผาผลาญดี อย่าเพิ่งเหลิง เดี๋ยวก็ถึงคิว' }
  if (age < 25) return { emoji: '🔥', text: 'ช่วงพีคของชีวิต กินอะไรก็ยังเอาอยู่ — ตอนนี้นะ' }
  if (age < 30) return { emoji: '⏳', text: 'ใกล้แก่แล้วนะ อีกไม่กี่ปีจะเริ่มรู้สึกว่ากินเท่าเดิมแต่พุงไม่เท่าเดิม' }
  if (age < 40) return { emoji: '👏', text: 'ดีนะ แก่แล้วยังห่วงสุขภาพ หลายคนวัยนี้ยอมแพ้ไปแล้ว' }
  if (age < 50) return { emoji: '🚨', text: 'แก่แล้วนะ รู้ตัวยัง? วัยนี้เมตาบอลิซึมลดลงราว 1-2% ทุก 10 ปี' }
  return { emoji: '🧓', text: 'แก่แล้วนะ รู้ตัวยัง? แต่วัยนี้ที่ยังขยับได้ถือว่าน่านับถือมาก' }
}

